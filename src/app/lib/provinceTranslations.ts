/**
 * Translate province name or stateId to Chinese.
 * Prioritizes stateId (from STATE_ID_CN_MAP) when available, so ID-specific renames always take effect.
 */
export function getProvinceChineseName(
 nameOrId: string | number | undefined | null,
 stateId?: string | number | null
): string {
 // 1. If explicit stateId is provided, check STATE_ID_CN_MAP first
 if (stateId !== undefined && stateId !== null && stateId !== '') {
  const sid = Number(stateId);
  if (!isNaN(sid) && STATE_ID_CN_MAP[sid]) {
   return STATE_ID_CN_MAP[sid];
  }
 }

 if (nameOrId === undefined || nameOrId === null || nameOrId === '') return '';
 
 // 2. If nameOrId itself is numeric, check STATE_ID_CN_MAP
 if (typeof nameOrId === 'number' || (!isNaN(Number(nameOrId)) && typeof nameOrId === 'string' && /^\d+$/.test(nameOrId.trim()))) {
  const sid = Number(nameOrId);
  if (STATE_ID_CN_MAP[sid]) {
   return STATE_ID_CN_MAP[sid];
  }
 }

 // 3. Check PROVINCE_CN_MAP
 const key = String(nameOrId).trim();
 if (PROVINCE_CN_MAP[key]) return PROVINCE_CN_MAP[key];

 // Try removing underscores or suffix if any
 const cleanKey = key.replace(/_/g, ' ');
 if (PROVINCE_CN_MAP[cleanKey]) return PROVINCE_CN_MAP[cleanKey];

 return key;
}
